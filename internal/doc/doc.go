// Package doc manages the generated HypeDoc block at the top of a markdown document.
package doc

import (
	"errors"
	"fmt"
	"html"
	"net/url"
	"strings"
)

const (
	startPrefix = "<!-- hypedoc:start"
	StartMarker = "<!-- hypedoc:start -->"
	EndMarker   = "<!-- hypedoc:end -->"
)

// Image is one rendered graphic. Paths are relative to the document, slash-separated.
type Image struct {
	Alt   string
	Light string // always set; used as the fallback <img>
	Dark  string // optional; emitted as a prefers-color-scheme: dark <source>
	Width int    // CSS width the graphic was designed at
}

// RenderBlock builds the managed block (markers included, no trailing newline).
func RenderBlock(imgs []Image) string {
	var b strings.Builder
	b.WriteString(StartMarker + "\n")
	b.WriteString("<!-- Generated by HypeDoc. Edit the .html sources and run `hypedoc build`; changes inside this block are overwritten. -->\n")
	for _, img := range imgs {
		alt := html.EscapeString(img.Alt)
		tag := fmt.Sprintf(`<img src="%s" alt="%s" width="%d">`, escapePath(img.Light), alt, img.Width)
		b.WriteString("<p align=\"center\">\n")
		if img.Dark != "" {
			b.WriteString("  <picture>\n")
			fmt.Fprintf(&b, "    <source media=\"(prefers-color-scheme: dark)\" srcset=\"%s\">\n", escapePath(img.Dark))
			fmt.Fprintf(&b, "    <source media=\"(prefers-color-scheme: light)\" srcset=\"%s\">\n", escapePath(img.Light))
			b.WriteString("    " + tag + "\n")
			b.WriteString("  </picture>\n")
		} else {
			b.WriteString("  " + tag + "\n")
		}
		b.WriteString("</p>\n")
	}
	b.WriteString(EndMarker)
	return b.String()
}

// Inject replaces an existing managed block in src, or prepends one (after any
// YAML front matter). Everything outside the block is preserved byte for byte.
func Inject(src, block string) (string, error) {
	start, end, err := find(src)
	if err != nil {
		return "", err
	}
	if start >= 0 {
		return src[:start] + block + src[end:], nil
	}
	fm, rest := splitFrontMatter(src)
	if rest == "" {
		return fm + block + "\n", nil
	}
	return fm + block + "\n\n" + rest, nil
}

// Strip removes the managed block and the blank lines that follow it.
func Strip(src string) (string, bool, error) {
	start, end, err := find(src)
	if err != nil || start < 0 {
		return src, false, err
	}
	rest := src[end:]
	for i := 0; i < 2 && strings.HasPrefix(rest, "\n"); i++ {
		rest = rest[1:]
	}
	return src[:start] + rest, true, nil
}

// find locates the managed block. Markers only count when they start a line
// outside fenced code, so docs can mention them in prose or examples.
func find(src string) (start, end int, err error) {
	start = -1
	fence := ""
	for off := 0; off < len(src); {
		nl := strings.IndexByte(src[off:], '\n')
		lineEnd := len(src)
		if nl >= 0 {
			lineEnd = off + nl
		}
		line := strings.TrimRight(src[off:lineEnd], "\r")
		trimmed := strings.TrimLeft(line, " ")
		switch {
		case fence != "":
			if strings.HasPrefix(trimmed, fence) {
				fence = ""
			}
		case strings.HasPrefix(trimmed, "```"), strings.HasPrefix(trimmed, "~~~"):
			fence = trimmed[:3]
		case start < 0 && strings.HasPrefix(line, startPrefix):
			start = off
		case start >= 0 && strings.HasPrefix(line, EndMarker):
			return start, off + len(EndMarker), nil
		}
		off = lineEnd + 1
	}
	if start >= 0 {
		return -1, -1, errors.New("found hypedoc:start without hypedoc:end; fix the document by hand")
	}
	return -1, -1, nil
}

func splitFrontMatter(src string) (fm, rest string) {
	if !strings.HasPrefix(src, "---\n") {
		return "", src
	}
	i := strings.Index(src[4:], "\n---\n")
	if i < 0 {
		return "", src
	}
	cut := 4 + i + len("\n---\n")
	return src[:cut] + "\n", strings.TrimLeft(src[cut:], "\n")
}

func escapePath(p string) string {
	return (&url.URL{Path: p}).EscapedPath()
}
